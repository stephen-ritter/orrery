"""The scenario ships the organs it grows: the build list is a derived artifact.

Rung two of the source-of-truth ladder (docs/what_the_scenario_rules.md). The
wake list already decides what the core boots (codegen/emit_startup); it now
also decides what the mission COMPILES. The yard door lands this fragment
naming the apps the flying scenario can wake, and targets.cmake builds exactly
those - so a scenario that never grew the eye carries no cam object file to
boot, to link, or to lose. Remove the fragment and the mission builds the
all-parts union: the same fallback law as the build-time startup table, so a
hand-run compose yard still finds a complete spacecraft waiting.

The entailments are the build door for free: select_apps refuses, before cmake
ever runs, a vehicle that asks for a service its wake list cannot serve. What
the manifest cannot serve, it also must not compile.
"""

from __future__ import annotations

import argparse
import sys
import tomllib
from pathlib import Path

from codegen.emit_startup import AppRow, StartupDoorError, load_apps, select_apps
from sim.parts import REPO, Part, load_registry

DEFS = REPO / "cfs_mission" / "mission" / "orrery_defs"
APPLIST_FRAGMENT = DEFS / "mission_applist.cmake"


def build_apps(apps: list[AppRow], parts: list[Part], scenario: Path) -> list[str]:
    """The apps this scenario's fleet may compile to, in inventory order.

    One vehicle waking an app is enough to build it (a fleet shares one build
    plane); no vehicle waking it means no object file anywhere. Core-shipped
    apps answer for themselves - the core or the per-CPU lists build them -
    and every vehicle's entailments are checked on the way, so the door
    speaks for the build exactly as it speaks for the boot.
    """
    with scenario.open("rb") as fh:
        doc = tomllib.load(fh)
    crafts = [str(craft["name"]) for craft in doc.get("spacecraft", [])]
    if not crafts:
        raise StartupDoorError(f"{scenario.name}: no [[spacecraft]] to build for")
    woken: set[str] = set()
    for craft in crafts:
        woken.update(row.name for row in select_apps(apps, parts, scenario, craft))
    return [row.name for row in apps if not row.core_shipped and row.name in woken]


def render(names: list[str]) -> str:
    """The cmake fragment: one list, one header, no ceremony.

    No scenario name inside - the stamp is a content fact, and two scenarios
    that compile the same organs deserve the same provenance.
    """
    return (
        "# AUTO-GENERATED by codegen/emit_applist - DO NOT EDIT\n"
        "# The yard door lands this fragment for the flying scenario; with it\n"
        "# absent, targets.cmake builds the all-parts union.\n"
        "set(ORRERY_SCENARIO_APPLIST " + " ".join(names) + ")\n"
    )


def write_fragment(
    scenario: Path,
    apps: list[AppRow] | None = None,
    parts: list[Part] | None = None,
    path: Path = APPLIST_FRAGMENT,
) -> Path:
    """Land the build list beside the defs, sweeping whatever came before."""
    apps = apps if apps is not None else load_apps()
    parts = parts if parts is not None else load_registry()
    path.write_text(render(build_apps(apps, parts, scenario)), encoding="utf-8")
    return path


def sweep_fragment(path: Path = APPLIST_FRAGMENT) -> None:
    """A yard down leaves the tree at the union default, like a page refreshed."""
    path.unlink(missing_ok=True)


def main(argv: list[str] | None = None) -> int:
    """CLI entry: land or sweep the scenario's build fragment."""
    ap = argparse.ArgumentParser(
        prog="emit_applist",
        description="cut the mission's app list to one scenario (rung two)",
    )
    ap.add_argument("--scenario", type=Path, help="scenario TOML to build for")
    ap.add_argument(
        "--out",
        type=Path,
        default=APPLIST_FRAGMENT,
        help=f"fragment path (default {APPLIST_FRAGMENT.relative_to(REPO)})",
    )
    ap.add_argument("--sweep", action="store_true", help="remove the fragment and exit")
    args = ap.parse_args(argv)
    if args.sweep:
        sweep_fragment(args.out)
        return 0
    if args.scenario is None:
        ap.error("one is needed: --scenario names the world to build for, --sweep sweeps it")
    if not args.scenario.is_file():
        print(f"emit_applist: no scenario at {args.scenario}", file=sys.stderr)
        return 2
    try:
        names = build_apps(load_apps(), load_registry(), args.scenario)
    except StartupDoorError as exc:
        print(f"emit_applist: {exc}", file=sys.stderr)
        return 1
    path = args.out
    path.write_text(render(names), encoding="utf-8")
    print(f"emit_applist: {args.scenario.name} -> {path.name} ({len(names)} apps)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
