"""Generate the registry's flight-side identity surfaces.

registry/parts.toml is the source. Every LANDED row whose consumer is
``bsk_link`` is rendered onto every surface a part needs to exist in the
firmware:

  - ``orrery_frames.h``      the world-frame table for the generic consumer
  - ``orrery_part_topicids.h``  mission topic IDs (flight-C mirror)
  - ``orrery_part_msgids.h``    SB MsgIds derived from those topics
  - ``cfe-topicids.xml``        the <Define> region between the GENERATED
    markers (EdsLib + ground defs read this file)

A part joins the airgap fleet by landing its registry row and re-running
this generator: zero C edits, zero hand-edited identity lines. App topics
(fcs, obc_hk, sps, the link control frames) are NOT parts and stay
hand-written; the generated region and headers sit beside them.

The C side (bsk_link.c) resolves each container against the linked EDS
database at startup and REFUSES a row whose real size differs from the
registry's - so the table, the schema, and the registry must all agree at
boot, not merely at commit time.

    uv run python -m codegen.emit_frames
"""

from __future__ import annotations

from sim.parts import REPO, Part, load_registry, registry_digest
from sim.parts import frame_rows as registry_frame_rows

DEFS = REPO / "cfs_mission" / "mission" / "orrery_defs"
OUT = DEFS / "inc" / "orrery_frames.h"
OUT_TOPICIDS = DEFS / "inc" / "orrery_part_topicids.h"
OUT_MSGIDS = DEFS / "inc" / "orrery_part_msgids.h"
TOPICIDS_XML = DEFS / "eds" / "cfe-topicids.xml"

# markers of the generated region inside the hand-written topicids XML;
# the region is replaced wholesale, the markers themselves stay
XML_BEGIN = "    <!-- BEGIN GENERATED (codegen/emit_frames.py): registered part topics -->"
XML_END = "    <!-- END GENERATED (codegen/emit_frames.py): registered part topics -->"

_GENERATED = "Generated by codegen/emit_frames.py from registry/parts.toml - DO NOT EDIT."

_HEADER = f"""/* {_GENERATED}
 *
 * World-frame table for bsk_link's generic frame consumer: one row per
 * registered part whose frames cross the airgap onto the bus. To onboard a
 * part: land its registry row, re-run codegen/emit_frames.py, rebuild - no C
 * edits. bsk_link resolves every container by name against the linked EDS
 * database at startup and disables any row whose size disagrees with this
 * table (naming the part on the event bus), so registry, schema, and binary
 * are mutually checked at boot, not just at commit time.
 */
#ifndef ORRERY_FRAMES_H
#define ORRERY_FRAMES_H

#include "cfe.h"
#include "orrery_msgids.h"
"""


def frame_rows(parts: list[Part]) -> list[Part]:
    """The registry rows that exist in firmware: landed, consumer bsk_link.

    The predicate lives in ``sim.parts`` (the sim's fit mask uses the same
    order, so a bit index means the same part on both sides of the airgap);
    this wrapper adds what only a generator cares about: a row that reaches
    firmware must carry its whole identity.

    Registry order (not sorted): the generated text mirrors the catalog's
    own order, so a reader can diff the file against the TOML line by line.
    """
    rows = registry_frame_rows(parts)
    for row in rows:
        if not (row.evs_info and row.evs_info_id and row.evs_label):
            raise ValueError(
                f"{row.name}: consumer=bsk_link needs evs_info, evs_info_id, evs_label"
            )
        if not (row.topic_name and row.mid_name and row.topic_offset):
            raise ValueError(f"{row.name}: consumer=bsk_link needs topic and MsgId identity")
    return rows


def table_row(part: Part) -> str:
    """One C initializer, with the registry row's name above it for the reader."""
    return (
        f"    /* name: {part.name} - {part.display} */\n"
        f'    {{ "{part.zmq_topic}", "{part.eds_container}", {part.mid_name}_MID,\n'
        f"      /* evs */ {part.container_bytes}, {part.evs_info_id} /* {part.evs_info} */,\n"
        f'      "{part.evs_label}" }},'
    )


def emit_frames_header(parts: list[Part]) -> str:
    """Render the whole generated header; only LANDED bsk_link rows are tabled."""
    rows = frame_rows(parts)
    max_payload = max((p.container_bytes for p in rows), default=0)
    lines = [_HEADER]
    lines.append(f"#define BSK_LINK_FRAME_ROWS {len(rows)}\n")
    lines.append(f"#define BSK_LINK_FRAME_MAX_PAYLOAD {max_payload}\n\n")
    lines.append(
        "/* Fit handshake: the digest of this table's SEMANTICS (row order,\n"
        " * topics, containers, sizes, MsgIds, EVS ids - not comments). The world\n"
        " * recomputes it from the registry it loaded and ships it in every\n"
        " * FitManifest; a mismatch means one side is stale, which no size check\n"
        " * can see (a stale binary is perfectly self-consistent). Rebuild:\n"
        " * uv run python -m codegen.emit_frames, then cfs_mission/build.sh. */\n"
        f"#define BSK_LINK_FIT_REGISTRY_HASH 0x{registry_digest(parts)}u\n\n"
    )
    lines.append(
        "typedef struct\n"
        "{\n"
        "    const char *Topic;     /* ZMQ multipart frame 1                                */\n"
        "    const char *Container; /* EDS type name, resolved against the linked database    */\n"
        "    uint16      Mid;       /* SB MsgId (generated orrery_part_msgids.h)              */\n"
        "    uint16      Size;      /* payload bytes; EDS must agree at startup or row off    */\n"
        "    uint16      EvsId;     /* first/every-N EVS event identity                       */\n"
        "    const char *Label;     /* operator text for the event line                       */\n"
        "} BskLink_WorldFrameDef_t;\n\n"
    )
    lines.append(
        "static const BskLink_WorldFrameDef_t BskLink_WorldFrames[BSK_LINK_FRAME_ROWS] = {\n"
    )
    for row in rows:
        lines.append(table_row(row) + "\n")
    lines.append("};\n\n#endif /* ORRERY_FRAMES_H */\n")
    return "".join(lines)


def emit_part_topicids(parts: list[Part]) -> str:
    """Topic IDs of the registered parts: the same numbers the XML carries."""
    rows = frame_rows(parts)
    lines = [
        f"/* {_GENERATED}\n"
        " *\n"
        " * Topic IDs of the registered observability parts, at\n"
        " * CFE_MISSION/TELEMETRY_BASE_TOPICID + offset. The hand-written\n"
        " * orrery_topicids.h includes this file; app topics (fcs, obc_hk, sps,\n"
        " * the link control frames) stay hand-written because apps are not\n"
        " * parts. Landing a part = one registry row + re-run, never an edit.\n"
        " */\n"
        "#ifndef ORRERY_PART_TOPICIDS_H\n"
        "#define ORRERY_PART_TOPICIDS_H\n\n"
    ]
    for row in rows:
        lines.append(f"/* part: {row.name} - {row.display} */\n")
        lines.append(f"#define CFE_MISSION_{row.topic_name} {row.topic_offset}\n\n")
    lines.append("#endif /* ORRERY_PART_TOPICIDS_H */\n")
    return "".join(lines)


def emit_part_msgids(parts: list[Part]) -> str:
    """SB MsgIds of the registered parts, base + topic like every custom MID."""
    rows = frame_rows(parts)
    lines = [
        f"/* {_GENERATED}\n"
        " *\n"
        " * MsgIds of the registered parts: target tlm MID base plus the topic\n"
        " * ID, the identical construction the hand-written orrery_msgids.h\n"
        " * uses for the app messages. Ground definitions generated by\n"
        " * codegen/eds2cosmos carry the same numbers, pinned by golden tests.\n"
        " */\n"
        "#ifndef ORRERY_PART_MSGIDS_H\n"
        "#define ORRERY_PART_MSGIDS_H\n\n"
        '#include "cfe_core_api_base_msgids.h"\n'
        '#include "orrery_part_topicids.h"\n\n'
    ]
    for row in rows:
        lines.append(f'/** \\brief {row.display} (part "{row.name}") */\n')
        lines.append(
            f"#define {row.mid_name}_MID "
            f"(SAMPLE_CPU1_TLM_MID_BASE + CFE_MISSION_{row.topic_name})\n\n"
        )
    lines.append("#endif /* ORRERY_PART_MSGIDS_H */\n")
    return "".join(lines)


def render_topicids_xml(xml: str, parts: list[Part]) -> str:
    """Replace the GENERATED region of cfe-topicids.xml with the registry."""
    rows = frame_rows(parts)
    if XML_BEGIN not in xml or XML_END not in xml:
        raise ValueError("cfe-topicids.xml lost its GENERATED part-topic markers")
    width = max((len(f'{r.topic_name}"') for r in rows), default=0)
    block = [XML_BEGIN]
    for row in rows:
        pad = " " * (width - len(f'{row.topic_name}"') + 1)
        block.append(
            f'    <Define name="{row.topic_name}"{pad}'
            f'value="${{CFE_MISSION/TELEMETRY_BASE_TOPICID}} + {row.topic_offset}" />'
        )
    block.append(XML_END)
    start = xml.index(XML_BEGIN)
    end = xml.index(XML_END) + len(XML_END)
    return xml[:start] + "\n".join(block) + xml[end:]


def main() -> int:
    """Write every registry-derived surface where the build will find it."""
    parts = load_registry()
    OUT.write_text(emit_frames_header(parts))
    OUT_TOPICIDS.write_text(emit_part_topicids(parts))
    OUT_MSGIDS.write_text(emit_part_msgids(parts))
    TOPICIDS_XML.write_text(render_topicids_xml(TOPICIDS_XML.read_text(), parts))
    rows = len(frame_rows(parts))
    for path in (OUT, OUT_TOPICIDS, OUT_MSGIDS, TOPICIDS_XML):
        print(f"{rows} part rows -> {path.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
