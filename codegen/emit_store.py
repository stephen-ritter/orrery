"""The recorder each vehicle ships is a scenario fact: land it for the build.

``[[store]]`` sizes a vehicle's recorder, and a size the craft does not carry
is a number nobody obeys. This module turns the flying scenario's store rows
into a header the mission build compiles in, so "the binary that flew knew its
recorder's size" is a provenance question rather than a hope: change the
scenario's capacity, and the firmware stamp moves with it - exactly like the
applist fragment and the per-vehicle startup table.

The law is checked here too, in the yard's own words: an outlet that writes
bytes (``record_rate`` > 0) on a vehicle with no sized recorder is refused
before anything compiles. bskforge's schema refuses the same document at load;
this is the copy of the law that lives on our side of the dependency, so a
bump upstream cannot quietly soften it.

With no scenario named (a hand-run build) the header carries no rows, which
means no vehicle claims a recorder: the same "union default" the applist
fragment uses, stated in the file rather than assumed.
"""

from __future__ import annotations

import argparse
import sys
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
DEFS = REPO / "cfs_mission" / "mission" / "orrery_defs"
OUT = DEFS / "inc" / "orrery_store.h"

_GENERATED = "Generated by codegen/emit_store.py from the flying scenario - DO NOT EDIT."

_GUARD = """/* {generated}
 *
 * The recorders this scenario's vehicles ship. One row per vehicle and
 * payload: two eyes on one vehicle write into one store, so they share one
 * budget. bsk_link looks up its own vehicle (ORRERY_VEHICLE) and enforces the
 * row at the moment a capture would land: recycle the oldest file the ground
 * has proven it holds, otherwise refuse the frame and say so.
{body}
 */
#ifndef ORRERY_STORE_H
#define ORRERY_STORE_H

#include "cfe.h"

typedef struct
{{
    const char* Vehicle;  /* [[spacecraft]] name, matched against ORRERY_VEHICLE */
    const char* Payload;  /* the payload that owns the bytes */
    uint64      CapacityBytes;
    uint32      CapacityFiles;
}} OrreryStoreRow_t;

static const OrreryStoreRow_t OrreryStore_Rows[] = {{
{rows}
}};

#define ORRERY_STORE_ROW_COUNT (sizeof(OrreryStore_Rows) / sizeof(OrreryStore_Rows[0]))

#endif /* ORRERY_STORE_H */
"""

_UNION_NOTE = """ *
 * No scenario was named when this landed, so no vehicle claims a recorder.
 * A yard that boots a scenario gets this file rewritten by scripts/fleet.sh
 * before the image builds."""

_ROW_NOTE = """ *
 * Landed for {scenario}: {count} recorder row(s). The outlets that write
 * these bytes are declared in the same file that sizes the store."""


class StoreDoorError(ValueError):
    """The scenario cannot be built: its store law does not hold."""


#: The file cap the flight ledger can actually index (bsk_link's
#: BSK_LINK_STORE_LEDGER_MAX, and cam's manifest walk budget before it).
#: A scenario may claim less; more would be a bound nothing enforces.
LEDGER_REACH = 512


def store_rows(scenario: Path) -> list[tuple[str, str, int, int]]:
    """The scenario's ``[[store]]`` rows, with the yard's law checked.

    Raises:
        StoreDoorError: a vehicle records without declaring a sized recorder.
    """
    with scenario.open("rb") as fh:
        doc = tomllib.load(fh)

    rows: list[tuple[str, str, int, int]] = []
    for row in doc.get("store", []):
        vehicle = str(row.get("parent", ""))
        payload = str(row.get("payload", "cam"))
        nbytes = int(row.get("capacity_bytes", 0))
        nfiles = int(row.get("capacity_files", 0))
        if not vehicle:
            raise StoreDoorError(f"{scenario.name}: a [[store]] row names no parent")
        if nbytes <= 0 or nfiles <= 0:
            raise StoreDoorError(
                f"{scenario.name}: store {vehicle}/{payload} is not sized "
                f"({nbytes} bytes, {nfiles} files)"
            )
        if nfiles > LEDGER_REACH:
            raise StoreDoorError(
                f"{scenario.name}: store {vehicle}/{payload} claims {nfiles} "
                f"files; the onboard ledger indexes {LEDGER_REACH} - a recorder "
                "beyond its own index cannot honor its bounds"
            )
        rows.append((vehicle, payload, nbytes, nfiles))

    keyed = [(row[0], row[1]) for row in rows]
    dupes = sorted(
        {
            f"{vehicle}/{payload}"
            for vehicle, payload in keyed
            if keyed.count((vehicle, payload)) > 1
        }
    )
    if dupes:
        raise StoreDoorError(
            f"{scenario.name}: one recorder per vehicle and payload - two rows "
            f"are two truths about one store: {dupes}"
        )

    recording = {
        str(camera["parent"])
        for camera in doc.get("camera", [])
        if int(camera.get("record_rate", 0)) > 0
    }
    missing = sorted(recording - {row[0] for row in rows})
    if missing:
        raise StoreDoorError(
            f"{scenario.name}: outlets write bytes with no sized recorder for {missing}"
        )
    return rows


def render(rows: list[tuple[str, str, int, int]], scenario: str | None) -> str:
    """The header text, with the union case stated rather than left blank."""
    body = _ROW_NOTE.format(scenario=scenario, count=len(rows)) if rows else _UNION_NOTE
    if rows:
        lines = ",\n".join(
            f'    {{"{vehicle}", "{payload}", {nbytes}ULL, {nfiles}U}}'
            for vehicle, payload, nbytes, nfiles in rows
        )
    else:
        lines = '    {"", "", 0ULL, 0U} /* no rows: a vehicle never matches an empty name */'
    return _GUARD.format(generated=_GENERATED, body=body, rows=lines)


def write_header(scenario: Path | None, path: Path = OUT) -> Path:
    """Land the header for one scenario, or the union default for none."""
    rows = store_rows(scenario) if scenario is not None else []
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(rows, scenario.name if scenario is not None else None), encoding="utf-8")
    return path


def sweep_header(path: Path = OUT) -> None:
    """A yard down leaves no scenario's recorder behind."""
    path.unlink(missing_ok=True)


def main(argv: list[str] | None = None) -> int:
    """CLI entry: land one scenario's store header, or the union default."""
    ap = argparse.ArgumentParser(prog="emit_store", description=__doc__.splitlines()[0])
    ap.add_argument("--scenario", type=Path, help="scenario TOML to size recorders for")
    ap.add_argument(
        "--out", type=Path, default=OUT, help=f"header path (default {OUT.relative_to(REPO)})"
    )
    ap.add_argument("--sweep", action="store_true", help="remove the header and exit")
    args = ap.parse_args(argv)

    try:
        if args.sweep:
            sweep_header(args.out)
            return 0
        if args.scenario and not args.scenario.exists():
            raise StoreDoorError(f"no such scenario: {args.scenario}")
        landed = write_header(args.scenario, args.out)
        print(f"landed {landed.relative_to(REPO)}")
        return 0
    except StoreDoorError as exc:
        print(f"emit_store: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
