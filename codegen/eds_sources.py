"""The single enumeration of this mission's EDS input files.

Two very different things are generated from the same EDS XML:

* ``codegen/eds_model.py`` -> COSMOS cmd/tlm definitions and the ``gs_tcp`` MsgId
  table (ground + flight-visible packets), and
* the EdsLib runtime database built by ``edslink/`` (what the Basilisk side and any
  EdsLib-aware tool use to put those same packets on a wire).

If their input lists ever disagree, flight software, COSMOS and the simulator are
describing different schemas and nothing fails loudly. So the list lives here once;
``edslink/eds_dirs.cmake`` is a generated mirror of it and ``tests/test_eds_link.py``
asserts the mirror is current.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
CFS = REPO / "cfs_mission/cFS"
MISSION_DEFS_EDS = REPO / "cfs_mission/mission/orrery_defs/eds"
CMAKE_MANIFEST = REPO / "edslink/eds_dirs.cmake"

HEADER = "# AUTO-GENERATED by codegen/eds_sources.py - DO NOT EDIT."


def core_xml_files(cfs_root: Path = CFS) -> list[Path]:
    """Module, app and message-header packages from the pinned cFS checkout."""
    found: list[Path] = []
    found += sorted(cfs_root.glob("cfe/modules/*/eds/*.xml"))
    found += sorted(cfs_root.glob("apps/*/eds/*.xml"))
    found += sorted((cfs_root / "tools/eds/cfecfs/edsmsg/eds").glob("*.xml"))
    return found


def mission_define_files(mission_eds_dir: Path = MISSION_DEFS_EDS) -> list[Path]:
    """Mission EDS packages: config/topic defines plus the custom apps.

    Since P3c the orrery_defs ``eds/`` directory holds the custom app
    packages too (``bsk_link.xml`` graduated from the link-only directory
    when its frames went on the Software Bus, ``fcs.xml`` is new). One
    directory, one list - ground defs and the EdsLib DB stay in lockstep.
    """
    return sorted(mission_eds_dir.glob("*.xml"))


def all_xml_files(
    cfs_root: Path = CFS,
    mission_eds_dir: Path = MISSION_DEFS_EDS,
) -> list[Path]:
    """Every EDS XML file this mission is built from."""
    core = core_xml_files(cfs_root)
    return core + mission_define_files(mission_eds_dir)


def db_source_dirs(
    cfs_root: Path = CFS,
    mission_eds_dir: Path = MISSION_DEFS_EDS,
) -> list[Path]:
    """Module directories for the EdsLib toolchain.

    ``edstool_find_eds_sources()`` inspects ``<DIR>/eds/``, so each entry is the
    parent of an ``eds/`` directory holding one of :func:`all_xml_files`.
    """
    xml = all_xml_files(cfs_root, mission_eds_dir)
    return sorted({path.parent.parent for path in xml})


def cmake_manifest(dirs: list[Path]) -> str:
    """Render the dir list as a CMake include anchored at ``ORRERY_REPO``."""
    lines = [
        HEADER,
        "# Mirrors codegen.eds_sources.db_source_dirs(); regenerate with",
        "#   uv run python -m codegen.eds_sources --write",
        "set(ORRERY_EDS_DIRS",
    ]
    lines += [f'    "${{ORRERY_REPO}}/{path.relative_to(REPO)}"' for path in dirs]
    lines += [")", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    """Write or check the CMake mirror of the EDS source list."""
    ap = argparse.ArgumentParser(prog="eds_sources", description=__doc__.splitlines()[0])
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="write edslink/eds_dirs.cmake")
    mode.add_argument("--check", action="store_true", help="fail if it is out of date")
    args = ap.parse_args(argv)
    want = cmake_manifest(db_source_dirs())
    current = CMAKE_MANIFEST.read_text() if CMAKE_MANIFEST.is_file() else None
    rel = CMAKE_MANIFEST.relative_to(REPO)

    if current == want:
        print(f"{rel} is current ({len(db_source_dirs())} dirs)")
        return 0
    if args.check:
        print(
            f"{rel} is out of date - run: uv run python -m codegen.eds_sources --write",
            file=sys.stderr,
        )
        return 1
    CMAKE_MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    CMAKE_MANIFEST.write_text(want)
    print(f"wrote {rel} ({len(db_source_dirs())} dirs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
